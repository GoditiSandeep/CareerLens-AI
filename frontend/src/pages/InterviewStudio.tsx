import { useCallback, useEffect, useRef, useState, type FormEvent } from "react";
import {
  aiStatus,
  interviewApi,
  type AiStatus,
  type InterviewFeedback,
  type InterviewReport,
  type InterviewSession,
} from "../lib/api";
import {
  ErrorBanner, GlassCard, ProgressBar, ScoreBadge, Reveal, TiltCard, useToast,
} from "../components/ui";

// ---- Interview categories & answer frameworks (deterministic study aids) ----
// These are coaching aids only; the score itself comes from the backend.
const CATEGORIES: { key: string; label: string; icon: string; blurb: string }[] = [
  { key: "behavioral", label: "Behavioral", icon: "◈", blurb: "Past experiences & teamwork" },
  { key: "technical", label: "Technical", icon: "⌘", blurb: "Role-specific problem solving" },
  { key: "hr", label: "HR / Basics", icon: "☺", blurb: "Motivation & background" },
  { key: "situational", label: "Situational", icon: "◊", blurb: "Hypothetical judgment calls" },
];

const FRAMEWORKS: Record<string, { name: string; steps: string[] }> = {
  behavioral: {
    name: "STAR",
    steps: [
      "Situation — set the context in one or two lines.",
      "Task — state your specific responsibility.",
      "Action — describe what YOU did (not the team).",
      "Result — quantify the outcome and what you learned.",
    ],
  },
  technical: {
    name: "Approach → Solution → Trade-offs",
    steps: [
      "Clarify — restate the problem and assumptions.",
      "Approach — explain your method before coding.",
      "Solution — walk through the key steps.",
      "Trade-offs — cover complexity and alternatives.",
    ],
  },
  hr: {
    name: "Reason → Evidence → Fit",
    steps: [
      "Reason — why this role/company appeals to you.",
      "Evidence — cite a concrete supporting example.",
      "Fit — connect your goals to the role.",
    ],
  },
  situational: {
    name: "Context → Stance → Action → Outcome",
    steps: [
      "Context — acknowledge the scenario's stakes.",
      "Stance — state the principle you'd apply.",
      "Action — list the steps you would take.",
      "Outcome — describe the intended result.",
    ],
  },
};

const DIFFICULTIES = ["easy", "medium", "hard"];

// ---- Minimal, dependency-free Web Speech API access (opt-in only) ----
interface SpeechRecognitionLike {
  lang: string;
  interimResults: boolean;
  continuous: boolean;
  start: () => void;
  stop: () => void;
  onresult: ((e: { results: ArrayLike<ArrayLike<{ transcript: string }>> }) => void) | null;
  onerror: (() => void) | null;
  onend: (() => void) | null;
}
function getSpeechRecognition(): (new () => SpeechRecognitionLike) | null {
  const w = window as unknown as {
    SpeechRecognition?: new () => SpeechRecognitionLike;
    webkitSpeechRecognition?: new () => SpeechRecognitionLike;
  };
  return w.SpeechRecognition ?? w.webkitSpeechRecognition ?? null;
}

function AiModeBanner({ status }: { status: AiStatus | null }) {
  if (!status) return null;
  const live = status.mode === "live";
  return (
    <div className={`card !p-3 text-sm ${live ? "!border-emerald-300 dark:!border-emerald-700" : ""}`}>
      <span className={`badge-${live ? "green" : "amber"} mr-2`}>
        {live ? "Live AI" : "Deterministic"}
      </span>
      <span className="muted">
        {live
          ? `Feedback is generated by the configured provider (${status.provider}).`
          : "No AI provider is configured, so feedback uses a transparent, rule-based scorer — clearly labelled, never presented as a live model evaluation."}
      </span>
    </div>
  );
}

function FeedbackCard({
  fb, isLast, onNext,
}: {
  fb: InterviewFeedback;
  isLast: boolean;
  onNext: () => void;
}) {
  return (
    <Reveal className="card space-y-3">
      <div className="flex items-center justify-between">
        <p className="section-title">Answer feedback</p>
        <ScoreBadge score={fb.score} />
      </div>
      <p className="text-sm text-slate-700 dark:text-slate-300">{fb.feedback}</p>
      <div className="rounded-lg border border-slate-200 p-3 dark:border-slate-700">
        <p className="text-xs font-semibold uppercase tracking-wide text-slate-500">
          Stronger answer (sample)
        </p>
        <p className="mt-1 whitespace-pre-wrap text-sm text-slate-600 dark:text-slate-300">
          {fb.improved_answer}
        </p>
      </div>
      <button className="btn-primary w-full" onClick={onNext}>
        {isLast ? "See final report →" : "Next question →"}
      </button>
    </Reveal>
  );
}

type Phase = "setup" | "active" | "report";

export default function InterviewStudio() {
  const notify = useToast();

  const [status, setStatus] = useState<AiStatus | null>(null);
  const [session, setSession] = useState<InterviewSession | null>(null);
  const [feedback, setFeedback] = useState<InterviewFeedback | null>(null);
  const [report, setReport] = useState<InterviewReport | null>(null);
  const [history, setHistory] = useState<InterviewSession[]>([]);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");

  // Setup form
  const [role, setRole] = useState("Software Engineer");
  const [difficulty, setDifficulty] = useState("medium");
  const [category, setCategory] = useState("behavioral");

  // Active session
  const [qIndex, setQIndex] = useState(0);
  const [answer, setAnswer] = useState("");
  const [listening, setListening] = useState(false);
  const recRef = useRef<SpeechRecognitionLike | null>(null);

  const loadHistory = useCallback(async () => {
    try {
      setHistory(await interviewApi.list());
    } catch {
      /* history is non-critical */
    }
  }, []);

  useEffect(() => {
    aiStatus().then(setStatus).catch(() => setStatus(null));
    void loadHistory();
  }, [loadHistory]);

  const questions = session?.questions ?? [];
  const total = questions.length;
  const current = qIndex >= 0 && qIndex < total ? questions[qIndex] : null;
  const phase: Phase = !session ? "setup" : report ? "report" : "active";

  const start = async (e: FormEvent) => {
    e.preventDefault();
    setBusy(true);
    setError("");
    try {
      const s = await interviewApi.start({ role, difficulty, interview_type: category });
      setSession(s);
      setQIndex(0);
      setAnswer("");
      setFeedback(null);
      setReport(null);
      notify("Interview started. Good luck!", "success");
    } catch (err) {
      const msg = err instanceof Error ? err.message : "Could not start the interview";
      setError(msg);
      notify(msg, "error");
    } finally {
      setBusy(false);
    }
  };

  const submit = async (e: FormEvent) => {
    e.preventDefault();
    if (!session || !current || !answer.trim()) return;
    setBusy(true);
    setError("");
    try {
      const fb = await interviewApi.answer(session.id, answer.trim());
      setFeedback(fb);
      setAnswer("");
      if (fb.completed) {
        const rep = await interviewApi.report(session.id);
        setReport(rep);
        await loadHistory();
        notify("Interview complete — here is your report", "success");
      }
    } catch (err) {
      const msg = err instanceof Error ? err.message : "Could not submit that answer";
      setError(msg);
      notify(msg, "error");
    } finally {
      setBusy(false);
    }
  };

  const next = () => {
    if (feedback?.completed) {
      setReport((r) => r ?? { report: "", status: "completed" });
      return;
    }
    setQIndex((i) => Math.min(i + 1, Math.max(0, total - 1)));
    setFeedback(null);
  };

  const reset = () => {
    setSession(null);
    setFeedback(null);
    setReport(null);
    setAnswer("");
    setQIndex(0);
    void loadHistory();
  };

  const toggleVoice = () => {
    const Ctor = getSpeechRecognition();
    if (!Ctor) {
      notify("Speech input isn't supported in this browser", "error");
      return;
    }
    if (listening) {
      recRef.current?.stop();
      setListening(false);
      return;
    }
    const rec = new Ctor();
    rec.lang = "en-US";
    rec.interimResults = false;
    rec.continuous = false;
    rec.onresult = (e) => {
      const transcript = e.results[0]?.[0]?.transcript ?? "";
      setAnswer((a) => (a ? `${a} ${transcript}` : transcript));
    };
    rec.onerror = () => {
      setListening(false);
      notify("Speech capture failed", "error");
    };
    rec.onend = () => setListening(false);
    recRef.current = rec;
    rec.start();
    setListening(true);
  };

  return (
    <div className="space-y-6">
      <div>
        <h1 className="page-title">Interview Studio</h1>
        <p className="page-sub">
          Practice realistic, role-specific questions and get structured feedback on
          relevance, clarity, and completeness. Scores are guidance, not verdicts.
        </p>
      </div>

      <AiModeBanner status={status} />

      {error && <ErrorBanner message={error} onRetry={() => setError("")} />}

      {phase === "setup" && (
        <div className="grid gap-6 lg:grid-cols-3">
          <Reveal className="card lg:col-span-2">
            <p className="section-title mb-3">Set up your practice session</p>
            <form onSubmit={start} className="space-y-4">
              <div>
                <label className="label" htmlFor="role">Target role</label>
                <input id="role" className="input" value={role} required
                  placeholder="e.g. Software Engineer"
                  onChange={(e) => setRole(e.target.value)} />
              </div>
              <div>
                <label className="label">Question category</label>
                <div className="grid gap-2 sm:grid-cols-2">
                  {CATEGORIES.map((c) => (
                    <button key={c.key} type="button"
                      onClick={() => setCategory(c.key)}
                      className={`rounded-lg border p-3 text-left transition-colors ${
                        category === c.key
                          ? "border-brand-500 bg-brand-50 dark:bg-slate-800"
                          : "border-slate-200 hover:border-slate-300 dark:border-slate-700"
                      }`}
                      aria-pressed={category === c.key}>
                      <span aria-hidden className="mr-1">{c.icon}</span>
                      <span className="font-medium">{c.label}</span>
                      <p className="muted mt-0.5 text-xs">{c.blurb}</p>
                    </button>
                  ))}
                </div>
              </div>
              <div>
                <label className="label" htmlFor="difficulty">Difficulty</label>
                <select id="difficulty" className="input" value={difficulty}
                  onChange={(e) => setDifficulty(e.target.value)}>
                  {DIFFICULTIES.map((d) => <option key={d} value={d}>{d}</option>)}
                </select>
              </div>
              <button className="btn-primary w-full" disabled={busy}>
                {busy ? "Preparing questions…" : "Start practice session"}
              </button>
            </form>
          </Reveal>

          <Reveal>
            <TiltCard>
              <GlassCard className="h-full" sheen>
                <p className="section-title mb-2">How to answer well</p>
                <p className="muted mb-3 text-xs">
                  Use a structured framework. This coaching is deterministic — the score
                  comes from the backend, and every suggestion is generic study guidance.
                </p>
                {FRAMEWORKS[category] && (
                  <div>
                    <p className="mb-1 text-sm font-semibold text-brand-700 dark:text-brand-300">
                      {FRAMEWORKS[category].name}
                    </p>
                    <ol className="space-y-1 text-sm text-slate-600 dark:text-slate-300">
                      {FRAMEWORKS[category].steps.map((s) => (
                        <li key={s} className="flex gap-2">
                          <span aria-hidden className="text-brand-500">•</span>{s}
                        </li>
                      ))}
                    </ol>
                  </div>
                )}
              </GlassCard>
            </TiltCard>
          </Reveal>
        </div>
      )}

      {phase === "active" && session && (
        <div className="space-y-5">
          <div className="card">
            <div className="mb-2 flex items-center justify-between text-sm">
              <span className="font-medium">
                Question {Math.min(qIndex + 1, total)} of {total}
              </span>
              <span className="muted">{session.role} · {session.difficulty}</span>
            </div>
            <ProgressBar value={total ? ((qIndex + (feedback ? 1 : 0)) / total) * 100 : 0} />
          </div>

          {!feedback && current && (
            <Reveal className="card space-y-4">
              <span className="badge-brand">{current.category}</span>
              <p className="text-lg font-medium text-slate-800 dark:text-slate-100">
                {current.question}
              </p>
              {FRAMEWORKS[current.category] && (
                <details className="rounded-lg bg-slate-50 p-3 text-sm dark:bg-slate-800">
                  <summary className="cursor-pointer font-medium">
                    Framework tip: {FRAMEWORKS[current.category].name}
                  </summary>
                  <ul className="mt-2 space-y-1 text-slate-600 dark:text-slate-300">
                    {FRAMEWORKS[current.category].steps.map((s) => <li key={s}>• {s}</li>)}
                  </ul>
                </details>
              )}
              <form onSubmit={submit} className="space-y-3">
                <label className="label" htmlFor="answer">Your answer</label>
                <textarea id="answer" className="input" rows={6} value={answer} required
                  placeholder="Type your answer, or use the mic if your browser supports it…"
                  onChange={(e) => setAnswer(e.target.value)} />
                <div className="flex flex-wrap items-center gap-2">
                  <button className="btn-primary" type="submit" disabled={busy || !answer.trim()}>
                    {busy ? "Scoring…" : "Submit answer"}
                  </button>
                  <button className="btn-ghost" type="button" onClick={toggleVoice}>
                    {listening ? "■ Stop mic" : "🎙 Use mic"}
                  </button>
                  {listening && <span className="pulse-dot" aria-label="listening" />}
                </div>
                <p className="muted text-xs">
                  Mic input uses your browser's built-in speech recognition when available
                  and only after you tap the button. No audio is stored.
                </p>
              </form>
            </Reveal>
          )}

          {feedback && current && (
            <FeedbackCard
              fb={feedback}
              isLast={feedback.completed}
              onNext={next}
            />
          )}
        </div>
      )}

      {phase === "report" && report && (
        <div className="space-y-4">
          <Reveal className="card">
            <p className="section-title mb-2">Session report</p>
            <p className="whitespace-pre-wrap text-sm text-slate-700 dark:text-slate-300">
              {report.report}
            </p>
            <button className="btn-primary mt-4" onClick={reset}>Start a new session</button>
          </Reveal>
        </div>
      )}

      {!session && history.length > 0 && (
        <div className="card">
          <p className="section-title mb-3">Your past sessions</p>
          <ul className="divide-y divide-slate-100 text-sm dark:divide-slate-800">
            {history.slice(0, 6).map((h) => (
              <li key={h.id} className="flex items-center justify-between py-2">
                <span>{h.role} <span className="muted">· {h.interview_type}</span></span>
                <span className="muted">{h.status}</span>
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}

